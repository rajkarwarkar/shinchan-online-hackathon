'use client';

import React, { useState } from 'react';
import { useDarkSpotStore } from '@/store/useDarkSpotStore';
import { X, Download, Copy, Check, FileText, Code2 } from 'lucide-react';

export const ReportExportModal: React.FC = () => {
  const { isExportModalOpen, setIsExportModalOpen, report, question, sources } = useDarkSpotStore();
  const [copied, setCopied] = useState(false);

  if (!isExportModalOpen || !report) return null;

  const generateMarkdown = () => {
    return `# DIGITAL DARK SPOT AUDIT REPORT
**Objective / Decision Goal:** ${question}
**Generated At:** ${new Date(report.generatedAt).toUTCString()}
**Completeness Index:** ${report.completenessIndex}% (Relative to reviewed sources)
**Model Info:** ${report.modelInfo}

---

## 1. Information Completeness & Coverage Summary
- Total Reviewed Sources: ${sources.length}
- Verified Sourced Claims: ${report.claims.filter((c) => c.quoteVerified).length}
- Critical Dark Spots (Gaps): ${report.gaps.length}
- Flagged Contradictions: ${report.conflicts.length}
- Temporal Freshness Alerts: ${report.freshness.length}

---

## 2. Identified Information Gaps (Dark Spots)
${report.gaps
  .map(
    (g, idx) => `### ${idx + 1}. [${g.severity.toUpperCase()}] ${g.title}
- **Why It Matters:** ${g.whyItMatters}
- **Explanation:** ${g.explanation}
- **Trust Level:** ${g.trust}
`
  )
  .join('\n')}

---

## 3. Flagged Policy Contradictions
${report.conflicts
  .map(
    (c, idx) => `### ${idx + 1}. [${c.type.toUpperCase()}] Severity: ${c.severity}
- **Claim A:** "${c.claimA.quote}" (Source: ${c.claimA.sourceId})
- **Claim B:** "${c.claimB.quote}" (Source: ${c.claimB.sourceId})
- **Possible Explanation:** ${c.possibleExplanation}
`
  )
  .join('\n')}

---

## 4. Prioritized Verification Checklist
${report.checklist
  .map(
    (item) => `- [${item.done ? 'x' : ' '}] **[${item.priority}]** ${item.action}
  - *Decision Impact:* ${item.why}
  - *Suggested Authority:* ${item.suggestedVerificationSource || 'Official Domain'}
`
  )
  .join('\n')}

---
*Disclaimer: Generated by Digital Dark Spot. AI-detected potential signals, not guaranteed legal or financial facts. Always confirm with official issuing authorities.*
`;
  };

  const downloadMarkdown = () => {
    const md = generateMarkdown();
    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `darkspot-audit-${Date.now()}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const downloadJSON = () => {
    const data = JSON.stringify(report, null, 2);
    const blob = new Blob([data], { type: 'application/json;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `darkspot-audit-${Date.now()}.json`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const copyToClipboard = async () => {
    const md = generateMarkdown();
    await navigator.clipboard.writeText(md);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-md animate-in fade-in duration-200">
      <div className="relative w-full max-w-xl rounded-3xl bg-[#0B0F14] border border-white/10 p-6 space-y-6 shadow-2xl">
        <div className="flex items-start justify-between">
          <div className="space-y-1">
            <h2 className="text-lg font-bold text-white flex items-center space-x-2">
              <Download className="w-5 h-5 text-amber-400" />
              <span>Export Audit Report</span>
            </h2>
            <p className="text-xs text-zinc-400">
              Download complete evidence traceability data and prioritized checklists.
            </p>
          </div>

          <button
            onClick={() => setIsExportModalOpen(false)}
            className="p-1.5 rounded-xl bg-white/5 hover:bg-white/10 text-zinc-400 hover:text-white transition-colors cursor-pointer"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        <div className="space-y-3">
          <button
            onClick={downloadMarkdown}
            className="w-full p-4 rounded-2xl bg-white/[0.03] hover:bg-white/[0.07] border border-white/10 flex items-center justify-between text-left transition-all cursor-pointer group"
          >
            <div className="flex items-center space-x-3">
              <div className="w-10 h-10 rounded-xl bg-amber-500/10 border border-amber-500/20 flex items-center justify-center text-amber-400">
                <FileText className="w-5 h-5" />
              </div>
              <div>
                <h4 className="text-sm font-bold text-white">Download Markdown (.md)</h4>
                <p className="text-xs text-zinc-400">Standard formatted report for documentation or GitHub</p>
              </div>
            </div>
            <Download className="w-4 h-4 text-zinc-500 group-hover:text-amber-400 transition-colors" />
          </button>

          <button
            onClick={downloadJSON}
            className="w-full p-4 rounded-2xl bg-white/[0.03] hover:bg-white/[0.07] border border-white/10 flex items-center justify-between text-left transition-all cursor-pointer group"
          >
            <div className="flex items-center space-x-3">
              <div className="w-10 h-10 rounded-xl bg-teal-500/10 border border-teal-500/20 flex items-center justify-center text-teal-400">
                <Code2 className="w-5 h-5" />
              </div>
              <div>
                <h4 className="text-sm font-bold text-white">Download Full JSON (.json)</h4>
                <p className="text-xs text-zinc-400">Structured data with claims, offsets, and coverage matrix</p>
              </div>
            </div>
            <Download className="w-4 h-4 text-zinc-500 group-hover:text-teal-400 transition-colors" />
          </button>

          <button
            onClick={copyToClipboard}
            className="w-full p-3 rounded-xl bg-white/5 hover:bg-white/10 border border-white/10 text-xs font-mono text-zinc-300 hover:text-white flex items-center justify-center space-x-2 transition-colors cursor-pointer"
          >
            {copied ? <Check className="w-4 h-4 text-emerald-400" /> : <Copy className="w-4 h-4 text-zinc-400" />}
            <span>{copied ? 'Copied to Clipboard!' : 'Copy Summary to Clipboard'}</span>
          </button>
        </div>
      </div>
    </div>
  );
};
